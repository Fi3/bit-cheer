#!/usr/bin/env python3
"""Fit Bit Cheer's small local rhythm model from its original authored corpus.

Each instrument is a binary, first-order Markov chain conditioned on sixteenth-
note position in the bar. Empirical phase frequencies are a weak prior for sparse
(previous-note, phase) observations. Inference is reproducible Rust, not a neural
network or a call to a hosted music generator. No third-party training data.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / "docs/rhythm-corpus.json"
OUTPUT = ROOT / "engine/src/rhythm_weights.rs"
INSTRUMENTS = ["kick", "hat", "snare", "clap", "bass", "perc", "synth"]
PRIOR_STRENGTH = 4.0


def fit(corpus: dict) -> list:
    patterns = corpus["patterns"]
    if len(patterns) < 8:
        raise ValueError("At least eight original patterns are required")
    counts = [[[[0, 0] for _ in range(2)] for _ in range(16)] for _ in INSTRUMENTS]
    for pattern in patterns:
        for instrument, name in enumerate(INSTRUMENTS):
            sequence = pattern[name]
            if len(sequence) % 16 or not sequence or set(sequence) - {"x", "-"}:
                raise ValueError(f"Invalid {name} pattern: {pattern['name']}")
            for step, note in enumerate(sequence):
                previous = int(sequence[(step - 1) % len(sequence)] == "x")
                counts[instrument][step % 16][previous][int(note == "x")] += 1
    weights = []
    for instrument in counts:
        phases = []
        for phase in instrument:
            hits = sum(pair[1] for pair in phase)
            total = sum(sum(pair) for pair in phase)
            marginal = (hits + 0.25) / (total + 0.5)
            phases.append([
                round(65535 * (pair[1] + PRIOR_STRENGTH * marginal) / (sum(pair) + PRIOR_STRENGTH))
                for pair in phase
            ])
        weights.append(phases)
    return weights


def render(raw: bytes) -> str:
    weights = fit(json.loads(raw))
    lines = [
        "// Generated by scripts/train-rhythm-model.py; do not edit by hand.",
        f"// Original authored corpus SHA-256: {hashlib.sha256(raw).hexdigest()}",
        "// P(hit | instrument, sixteenth-note phase, previous hit), scaled to 65535.",
        "#[rustfmt::skip]",
        "pub(crate) const PROBABILITIES: [[[u16; 2]; 16]; 7] = [",
    ]
    for name, instrument in zip(INSTRUMENTS, weights):
        lines.append("    [" + ", ".join(f"[{off}, {on}]" for off, on in instrument) + f"], // {name}")
    lines += [
        "];",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in weights reproduce exactly")
    args = parser.parse_args()
    raw = CORPUS.read_bytes()
    generated = render(raw)
    assert generated == render(raw), "Training must be deterministic"
    corpus = json.loads(raw)
    changed = json.loads(raw)
    changed["patterns"][0]["hat"] = "-" * len(changed["patterns"][0]["hat"])
    assert fit(changed) != fit(corpus), "Weights must depend on training examples"
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != generated:
            raise SystemExit("Rhythm weights are stale: run python3 scripts/train-rhythm-model.py")
        print(f"Rhythm model verified: {len(corpus['patterns'])} authored patterns; reproducible corpus-dependent weights")
    else:
        OUTPUT.write_text(generated)
        print(f"Trained {len(corpus['patterns'])} authored patterns -> {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
